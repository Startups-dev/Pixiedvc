create role authenticated nologin;
create role service_role nologin bypassrls;
create schema auth;
create table auth.users (id uuid primary key, email text);
create function auth.uid() returns uuid language sql stable as $$
  select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid;
$$;
create function auth.role() returns text language sql stable as $$ select current_user::text; $$;
grant usage on schema public, auth to anon, authenticated, service_role;
create table public.profiles (id uuid primary key references auth.users(id), role text);
create table public.resorts (id uuid primary key, name text not null);
create type public.booking_status as enum ('draft', 'submitted', 'cancelled');
create table public.booking_requests (id uuid primary key default gen_random_uuid(), status public.booking_status default 'draft', accepted_terms boolean default false, is_test_booking boolean not null default false);
